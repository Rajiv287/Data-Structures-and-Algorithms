/*
Question: Area of Square

Approach:
1. Input side of square
2. Multiply side by itself
3. Print the area

Time Complexity: O(1)
Space Complexity: O(1)
*/

// WAP to input the size of square and output the area of the square.
#include<iostream>
using namespace std;
int main (){
   int n;
   cout<<"enter the side of square ";
   cin>>n;
   cout<<"Area of square is = "<<n*n << endl; 

    return 0;
}
